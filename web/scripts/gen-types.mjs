// Generates lib/types.generated.ts from the site contract exported by the Python package
// (`soyforecast export-schema` -> lib/schema/site.schema.json). Never edit the output by hand:
// change src/soyforecast/publish/schema.py, re-export, then run `npm run gen:types`.
// `npm run gen:types -- --check` fails when the committed file is out of date (used in CI).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const schemaPath = path.join(root, "lib", "schema", "site.schema.json");
const outPath = path.join(root, "lib", "types.generated.ts");

// json-schema-to-typescript reads draft-07 tuples (`items: [...]`); pydantic writes 2020-12
// `prefixItems`. Translate so tuple[str, str] becomes [string, string], not [unknown, unknown].
function draft07Tuples(node) {
  if (Array.isArray(node)) return node.map(draft07Tuples);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) out[k === "prefixItems" ? "items" : k] = draft07Tuples(v);
  return out;
}

const schema = draft07Tuples(JSON.parse(fs.readFileSync(schemaPath, "utf-8")));

const banner = `// GENERATED by scripts/gen-types.mjs from lib/schema/site.schema.json. Do not edit.
// Source of truth: src/soyforecast/publish/schema.py (pydantic). Prices are US cents per bushel.`;

const ts = await compile(schema, "SiteData", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false, printWidth: 120 },
});
const text = ts.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf-8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("lib/types.generated.ts is out of date: run `npm run gen:types` and commit it.");
    process.exit(1);
  }
  console.log("lib/types.generated.ts is up to date.");
} else {
  fs.writeFileSync(outPath, text, "utf-8");
  console.log(`wrote ${path.relative(root, outPath)}`);
}
